// 「換你了」：對還不是代跑者的人顯示的那一塊邀請（web-spec §13）。
//
// **它不是說明，是邀請** —— 所以有動作按鈕。兩個地方用它：介紹頁，以及 job 跑完
// 的結果頁。後者是刻意的：招募的時機不是「他還不懂的時候」，是他**剛受惠、剛欠了
// 一杯**的時候。提交頁刻意沒有 —— 那一頁的情境是「我額度爆了」，他現在沒有額度。
//
// 按鈕指向 /worker 而不是登入頁：沒登入的話 Shell 會就地渲染登入表單，網址留在
// /worker，登入完就直接落在「我來代跑」。少一次「登入後還要自己找路」。

import { Link } from "react-router-dom";

export function YourTurn({ tone }: { tone: "after-job" | "intro" }) {
  return (
    <section className="yourturn">
      <h2>換你了？</h2>
      <p>
        {tone === "after-job"
          ? "剛才那一趟燒的是別人的額度。哪天你還有、別人沒有的時候，換你借出去。"
          : "額度還有的人，可以把它借出去 —— 別人的 job 會用你的帳號跑完，然後欠你一杯。"}
      </p>
      {/* 代價預告。**不講期限** —— 現在兩種憑證並存，期限因帳號而異，寫死任何
          一個天數都會對一半的人說謊（web-spec §13）。但不講期限不等於可以寫成
          「連結你的帳號」：沒有預告，下一頁那段正經揭露就會變成埋伏。 */}
      <p className="hint">
        會需要授權你的 Claude 帳號給這個站台，token 存在共用主機上。
        下一頁會講清楚它是什麼、誰拿得到。
      </p>
      <Link className="button-link" to="/worker">
        我來代跑
      </Link>
    </section>
  );
}
